static const char* FindSubstring(const char* text, const char* needle)
{
    size_t needleLength;

    needleLength = strlen(needle);

    if (needleLength == 0)
    {
        return text;
    }

    while (*text)
    {
        if (*text == *needle && memcmp(text, needle, needleLength) == 0)
        {
            return text;
        }

        ++text;
    }

    return NULL;
}

static int IsAppearanceNameCharacter(char value)
{
    return (value >= 'a' && value <= 'z') || (value >= 'A' && value <= 'Z') || (value >= '0' && value <= '9') || value == '_';
}

static const char* FindNamedAppearanceData(const char* text, const char* name)
{
    const char* match;
    const char* cursor;
    size_t nameLength;

    if (!text || !name || !name[0])
    {
        return NULL;
    }

    nameLength = strlen(name);
    match = text;

    while ((match = FindSubstring(match, name)) != NULL)
    {
        if ((match == text || !IsAppearanceNameCharacter(match[-1])) && !IsAppearanceNameCharacter(match[nameLength]))
        {
            cursor = match + nameLength;

            while (*cursor == ' ' || *cursor == '\t' || *cursor == '=')
            {
                ++cursor;
            }

            return cursor;
        }

        match += nameLength;
    }

    return NULL;
}

static int ReadNamedAppearanceValue(const char* text, const char* name, int* outValue)
{
    const char* cursor;
    unsigned int value;

    cursor = FindNamedAppearanceData(text, name);

    if (!cursor || *cursor < '0' || *cursor > '9')
    {
        return 0;
    }

    value = 0;

    while (*cursor >= '0' && *cursor <= '9')
    {
        value = value * 10U + (unsigned int)(*cursor - '0');

        if (value > APPEARANCE_MAX_ID)
        {
            value = APPEARANCE_MAX_ID;
            break;
        }

        ++cursor;
    }

    *outValue = (int)value;
    return 1;
}

static int ReadNamedAppearanceString(const char* text, const char* name, char* outValue, size_t outSize)
{
    const char* cursor;
    char terminator;
    size_t length;

    if (!outValue || outSize == 0)
    {
        return 0;
    }

    cursor = FindNamedAppearanceData(text, name);

    if (!cursor || !cursor[0])
    {
        return 0;
    }

    terminator = '\0';

    if (*cursor == '"' || *cursor == '\'')
    {
        terminator = *cursor;
        ++cursor;
    }

    length = 0;

    while (*cursor && ((terminator && *cursor != terminator) || (!terminator && *cursor != ' ' && *cursor != '\t' && *cursor != '\r' && *cursor != '\n' && *cursor != '}')))
    {
        if (length + 1 >= outSize)
        {
            return 0;
        }

        outValue[length++] = *cursor++;
    }

    if (length == 0 || (terminator && *cursor != terminator))
    {
        return 0;
    }

    outValue[length] = '\0';
    return 1;
}

static int ReadNamedAppearanceIDValue(const char* text, const char* name, AppearanceField field, int* outValue)
{
    char token[NAMED_ID_BUFFER_SIZE];
    int value;

    if (!outValue)
    {
        return 0;
    }

    if (ReadNamedAppearanceValue(text, name, &value))
    {
        *outValue = value;
        SetNamedAppearanceID(field, NULL);
        return 1;
    }

    if (!ReadNamedAppearanceString(text, name, token, sizeof(token)) || token[0] != '@' || !ResolveNamedAppearanceID(field, token, &value))
    {
        return 0;
    }

    *outValue = value;
    SetNamedAppearanceID(field, token);
    return 1;
}

static int ReadNamedAppearanceDouble(const char* text, const char* name, double* outValue)
{
    const char* cursor;
    double value;
    double place;
    int foundDigit;

    if (!outValue)
    {
        return 0;
    }

    cursor = FindNamedAppearanceData(text, name);

    if (!cursor)
    {
        return 0;
    }

    value = 0.0;
    foundDigit = 0;

    while (*cursor >= '0' && *cursor <= '9')
    {
        value = value * 10.0 + (double)(*cursor - '0');
        foundDigit = 1;
        ++cursor;
    }

    if (*cursor == '.')
    {
        ++cursor;
        place = 0.1;

        while (*cursor >= '0' && *cursor <= '9')
        {
            value += (double)(*cursor - '0') * place;
            place *= 0.1;
            foundDigit = 1;
            ++cursor;
        }
    }

    if (!foundDigit)
    {
        return 0;
    }

    *outValue = value;
    return 1;
}

static int LoadAppearanceFile(uint8_t* parts, int* defaultFrame, const char* path)
{
    AppearanceSnapshot appearance;
    char text[APPEARANCE_TEXT_BUFFER_SIZE];
    HANDLE file;
    DWORD fileSize;
    DWORD highSize;
    DWORD readSize;
    int fieldValue;
    double pitchValue;
    int loadedFields;

    file = CreateFileA(path, GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, NULL);

    if (file == INVALID_HANDLE_VALUE)
    {
        AddDebugMessage("Load failed: Could not open the selected file!");
        return 0;
    }

    highSize = 0;
    fileSize = GetFileSize(file, &highSize);

    if (fileSize == 0 || fileSize == INVALID_FILE_SIZE || highSize != 0 || fileSize >= (DWORD)sizeof(text))
    {
        CloseHandle(file);
        AddDebugMessage("Load failed: Invalid or oversized .catstruct file!");
        return 0;
    }

    readSize = 0;

    if (!ReadFile(file, text, fileSize, &readSize, NULL) || readSize != fileSize)
    {
        CloseHandle(file);
        AddDebugMessage("Load failed: The .catstruct file could not be read!");
        return 0;
    }

    CloseHandle(file);
    text[readSize] = '\0';

    if (!defaultFrame)
    {
        AddDebugMessage("Load failed: Default-frame state unavailable!");
        return 0;
    }

    *defaultFrame = APPEARANCE_DEFAULT_FRAME;

    ReadAppearance(parts, &appearance);
    loadedFields = 0;

    if (ReadNamedAppearanceValue(text, "claws", &fieldValue))
    {
        appearance.claws = ClampAppearanceID(fieldValue, CLAWS_ENABLED_VALUE);
        ++loadedFields;
    }

#define LOAD_APPEARANCE_FIELD(name, member, field) \
    do \
    { \
        if (ReadNamedAppearanceIDValue(text, name, field, &fieldValue)) \
        { \
            appearance.member = fieldValue; \
            ++loadedFields; \
        } \
    } while (0)

    LOAD_APPEARANCE_FIELD("texture", texture, APPEARANCE_FIELD_TEXTURE);
    LOAD_APPEARANCE_FIELD("palette", palette, APPEARANCE_FIELD_PALETTE);
    LOAD_APPEARANCE_FIELD("body", body, APPEARANCE_FIELD_BODY);
    LOAD_APPEARANCE_FIELD("head", head, APPEARANCE_FIELD_HEAD);
    LOAD_APPEARANCE_FIELD("tail", tail, APPEARANCE_FIELD_TAIL);
    LOAD_APPEARANCE_FIELD("leg1", leg1, APPEARANCE_FIELD_LEG1);
    LOAD_APPEARANCE_FIELD("leg2", leg2, APPEARANCE_FIELD_LEG2);
    LOAD_APPEARANCE_FIELD("arm1", arm1, APPEARANCE_FIELD_ARM1);
    LOAD_APPEARANCE_FIELD("arm2", arm2, APPEARANCE_FIELD_ARM2);
    LOAD_APPEARANCE_FIELD("lefteye", lefteye, APPEARANCE_FIELD_LEFTEYE);
    LOAD_APPEARANCE_FIELD("righteye", righteye, APPEARANCE_FIELD_RIGHTEYE);
    LOAD_APPEARANCE_FIELD("lefteyebrow", lefteyebrow, APPEARANCE_FIELD_LEFTEYEBROW);
    LOAD_APPEARANCE_FIELD("righteyebrow", righteyebrow, APPEARANCE_FIELD_RIGHTEYEBROW);
    LOAD_APPEARANCE_FIELD("leftear", leftear, APPEARANCE_FIELD_LEFTEAR);
    LOAD_APPEARANCE_FIELD("rightear", rightear, APPEARANCE_FIELD_RIGHTEAR);
    LOAD_APPEARANCE_FIELD("mouth", mouth, APPEARANCE_FIELD_MOUTH);
#undef LOAD_APPEARANCE_FIELD

    if (ReadNamedAppearanceString(text, "voice", appearance.voice, sizeof(appearance.voice)))
    {
        ++loadedFields;
    }

    if (ReadNamedAppearanceDouble(text, "pitch", &pitchValue))
    {
        appearance.voicePitch = ClampVoicePitch(pitchValue);
        ++loadedFields;
    }

    if (loadedFields == 0)
    {
        AddDebugMessage("Load failed: No fields were found!");
        return 0;
    }

    ApplyAppearance(parts, &appearance);
    memset(g_idInputStates, 0, sizeof(g_idInputStates));
    g_activeIDInput = APPEARANCE_FIELD_COUNT;
    g_selectedPresetName[0] = '\0';
    snprintf(g_activeAppearancePath, sizeof(g_activeAppearancePath), "%s", path);
    AddDebugMessage("Loaded %d fields from %s!", loadedFields, AppearanceFileName(path));
    Log("Loaded %d fields from %s!", loadedFields, path);
    return 1;
}

static int DeleteAppearanceFile(const char* path)
{
    if (!DeleteFileA(path))
    {
        AddDebugMessage("Delete failed: %s", AppearanceFileName(path));
        Log("Could not delete file %s (error %lu)!", path, GetLastError());
        return 0;
    }

    if (strcmp(g_activeAppearancePath, path) == 0)
    {
        g_activeAppearancePath[0] = '\0';
    }

    AddDebugMessage("Deleted cat: %s", AppearanceFileName(path));
    Log("Deleted cat file %s!", path);
    return 1;
}

int DrawSavedAppearanceFiles(uint8_t* parts, int* defaultFrame)
{
    WIN32_FIND_DATAA data;
    char directory[MAX_PATH + 32];
    char pattern[560];
    char path[800];
    char fileLabel[MAX_PATH + 64];
    char deleteLabel[96];
    float automaticSize[2];
    float fileNameSize[2];
    float deleteButtonSize[2];
    const char* preview;
    HANDLE search;
    int changed;
    int fileCount;
    int pathLength;
    int isActive;

    if (!parts || !defaultFrame || !g_imguiBeginCombo)
    {
        return 0;
    }

    automaticSize[0] = 0.0f;
    automaticSize[1] = 0.0f;
    fileNameSize[0] = DEBUG_FILE_NAME_WIDTH;
    fileNameSize[1] = 0.0f;
    deleteButtonSize[0] = DEBUG_DELETE_BUTTON_WIDTH;
    deleteButtonSize[1] = 0.0f;

    if (!EnsureAppearanceDirectory(directory, sizeof(directory)))
    {
        return 0;
    }

    preview = g_activeAppearancePath[0] ? AppearanceFileName(g_activeAppearancePath) : "select saved cat";
    SetNextItemWidth(DEBUG_PRESET_COMBO_WIDTH);

    if (!g_imguiBeginCombo("saved cats##saved_appearance_combo", preview, 0))
    {
        return 0;
    }

    snprintf(pattern, sizeof(pattern), "%s\\*.catstruct", directory);
    search = FindFirstFileA(pattern, &data);

    if (search == INVALID_HANDLE_VALUE)
    {
        g_imguiSelectable("No saved .catstruct files!##saved_appearance_empty", false, 0, automaticSize);
        EndImGuiCombo();
        return 0;
    }

    changed = 0;
    fileCount = 0;

    do
    {
        if ((data.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) != 0)
        {
            continue;
        }

        pathLength = snprintf(path, sizeof(path), "%s\\%s", directory, data.cFileName);

        if (pathLength <= 0 || (size_t)pathLength >= sizeof(path))
        {
            continue;
        }

        isActive = strcmp(g_activeAppearancePath, path) == 0;
        snprintf(fileLabel, sizeof(fileLabel), "%s%s##saved_appearance_file_%d", isActive ? "* " : "", data.cFileName, fileCount);

        if (g_imguiSelectable(fileLabel, isActive != 0, 0, fileNameSize))
        {
            if (LoadAppearanceFile(parts, defaultFrame, path))
            {
                changed = 1;
            }
        }

        g_imguiSameLine();
        AddHorizontalGap(DEBUG_HORIZONTAL_GAP);
        snprintf(deleteLabel, sizeof(deleteLabel), "DELETE##delete_saved_appearance_%d", fileCount);

        if (SelectableKeepPopupOpen(deleteLabel, false, deleteButtonSize))
        {
            DeleteAppearanceFile(path);
        }

        AddVerticalGap(DEBUG_FILE_ROW_VERTICAL_GAP);
        ++fileCount;
    } while (FindNextFileA(search, &data));

    FindClose(search);
    EndImGuiCombo();
    return changed;
}

int CopyAppearance(const uint8_t* parts)
{
    char text[APPEARANCE_TEXT_BUFFER_SIZE];
    int textLength;
    HANDLE memory;
    void* destination;
    void* ownerWindow;

    textLength = FormatAppearanceText(parts, text, sizeof(text));

    if (!textLength)
    {
        AddDebugMessage("Copy failed: Appearance text was too large!");
        return 0;
    }

    ownerWindow = GetActiveWindow();

    if (!OpenClipboard(ownerWindow))
    {
        AddDebugMessage("Copy failed: Clipboard is busy!");
        return 0;
    }

    if (!EmptyClipboard())
    {
        CloseClipboard();
        AddDebugMessage("Copy failed: Clipboard could not be cleared!");
        return 0;
    }

    memory = GlobalAlloc(GMEM_MOVEABLE, (size_t)textLength + 1U);
    destination = memory ? GlobalLock(memory) : NULL;

    if (!destination)
    {
        if (memory)
        {
            GlobalFree(memory);
        }

        CloseClipboard();
        AddDebugMessage("Copy failed: Clipboard memory unavailable!");
        return 0;
    }

    memcpy(destination, text, (size_t)textLength + 1U);
    GlobalUnlock(memory);

    if (!SetClipboardData(CF_TEXT, memory))
    {
        GlobalFree(memory);
        CloseClipboard();
        AddDebugMessage("Copy failed: Clipboard rejected the text!");
        return 0;
    }

    CloseClipboard();
    AddDebugMessage("Copied data to clipboard!");
    Log("Copied data to the clipboard!");
    return 1;
}

