static uint32_t UpdatePngCrc32(uint32_t crc, const uint8_t* data, size_t length)
{
    uint32_t value;
    int bit;

    while (length--)
    {
        crc ^= *data++;

        for (bit = 0; bit < 8; ++bit)
        {
            value = 0U - (crc & 1U);
            crc = (crc >> 1) ^ (0xEDB88320U & value);
        }
    }

    return crc;
}

static uint32_t PngAdler32(const uint8_t* data, size_t length)
{
    uint32_t first;
    uint32_t second;
    size_t block;

    first = 1U;
    second = 0U;

    while (length)
    {
        block = length > 5552U ? 5552U : length;
        length -= block;

        while (block--)
        {
            first += *data++;
            second += first;
        }

        first %= 65521U;
        second %= 65521U;
    }

    return (second << 16) | first;
}

static void StoreBigEndian32(uint8_t* output, uint32_t value)
{
    output[0] = (uint8_t)(value >> 24);
    output[1] = (uint8_t)(value >> 16);
    output[2] = (uint8_t)(value >> 8);
    output[3] = (uint8_t)value;
}

static int WriteFileBytes(HANDLE file, const void* data, size_t length)
{
    const uint8_t* cursor;
    DWORD block;
    DWORD written;

    cursor = (const uint8_t*)data;

    while (length)
    {
        block = length > 0x40000000U ? 0x40000000U : (DWORD)length;
        written = 0;

        if (!WriteFile(file, cursor, block, &written, NULL) || written != block)
        {
            return 0;
        }

        cursor += block;
        length -= block;
    }

    return 1;
}

static int WritePngChunk(HANDLE file, const char type[4], const uint8_t* data, size_t length)
{
    uint8_t lengthBytes[4];
    uint8_t crcBytes[4];
    uint32_t crc;

    if (length > 0xFFFFFFFFU)
    {
        return 0;
    }

    StoreBigEndian32(lengthBytes, (uint32_t)length);
    crc = UpdatePngCrc32(0xFFFFFFFFU, (const uint8_t*)type, 4);
    crc = UpdatePngCrc32(crc, data, length) ^ 0xFFFFFFFFU;
    StoreBigEndian32(crcBytes, crc);
    return WriteFileBytes(file, lengthBytes, sizeof(lengthBytes)) && WriteFileBytes(file, type, 4) && WriteFileBytes(file, data, length) && WriteFileBytes(file, crcBytes, sizeof(crcBytes));
}

static int WriteRgbaPng(const char* path, const uint8_t* pixels, int width, int height)
{
    static const uint8_t signature[8] = { 137U, 80U, 78U, 71U, 13U, 10U, 26U, 10U };
    static const uint8_t empty[1] = { 0U };
    uint8_t header[13];
    uint8_t* raw;
    uint8_t* compressed;
    uint8_t* output;
    const uint8_t* input;
    HANDLE file;
    size_t rowBytes;
    size_t rawSize;
    size_t blockCount;
    size_t compressedSize;
    size_t remaining;
    size_t blockSize;
    size_t row;
    uint32_t adler;
    uint16_t length16;
    int success;

    if (!path || !pixels || width <= 0 || height <= 0)
    {
        return 0;
    }

    rowBytes = (size_t)width * 4U;

    if (rowBytes / 4U != (size_t)width || (size_t)height > ((size_t)-1) / (rowBytes + 1U))
    {
        return 0;
    }

    rawSize = (rowBytes + 1U) * (size_t)height;
    blockCount = (rawSize + 65534U) / 65535U;

    if (blockCount > (((size_t)-1) - rawSize - 6U) / 5U)
    {
        return 0;
    }

    compressedSize = 2U + rawSize + blockCount * 5U + 4U;

    raw = (uint8_t*)malloc(rawSize);
    compressed = (uint8_t*)malloc(compressedSize);

    if (!raw || !compressed)
    {
        free(compressed);
        free(raw);
        return 0;
    }

    for (row = 0; row < (size_t)height; ++row)
    {
        raw[row * (rowBytes + 1U)] = 0U;
        memcpy(raw + row * (rowBytes + 1U) + 1U, pixels + row * rowBytes, rowBytes);
    }

    output = compressed;
    *output++ = 0x78U;
    *output++ = 0x01U;
    input = raw;
    remaining = rawSize;

    while (remaining)
    {
        blockSize = remaining > 65535U ? 65535U : remaining;
        *output++ = blockSize == remaining ? 1U : 0U;
        length16 = (uint16_t)blockSize;
        *output++ = (uint8_t)length16;
        *output++ = (uint8_t)(length16 >> 8);
        length16 = (uint16_t)~length16;
        *output++ = (uint8_t)length16;
        *output++ = (uint8_t)(length16 >> 8);
        memcpy(output, input, blockSize);
        output += blockSize;
        input += blockSize;
        remaining -= blockSize;
    }

    adler = PngAdler32(raw, rawSize);
    StoreBigEndian32(output, adler);
    output += 4;

    memset(header, 0, sizeof(header));
    StoreBigEndian32(header, (uint32_t)width);
    StoreBigEndian32(header + 4, (uint32_t)height);
    header[8] = 8U;
    header[9] = 6U;

    file = CreateFileA(path, GENERIC_WRITE, FILE_SHARE_READ, NULL, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);

    if (file == INVALID_HANDLE_VALUE)
    {
        free(compressed);
        free(raw);
        return 0;
    }

    success = WriteFileBytes(file, signature, sizeof(signature)) && WritePngChunk(file, "IHDR", header, sizeof(header)) && WritePngChunk(file, "IDAT", compressed, (size_t)(output - compressed)) && WritePngChunk(file, "IEND", empty, 0);
    CloseHandle(file);
    free(compressed);
    free(raw);

    if (!success)
    {
        DeleteFileA(path);
    }

    return success;
}

static int ReadScreenshotCurrentFrame(uint8_t** outPixels, int* outWidth, int* outHeight)
{
    GLboolean doubleBuffered;
    GLint viewport[4];
    GLint previousPackAlignment;
    GLint previousReadBuffer;
    GLenum captureBuffer;
    uint8_t* pixels;
    size_t pixelCount;
    int width;
    int height;

    if (!outPixels || !outWidth || !outHeight)
    {
        return 0;
    }

    *outPixels = NULL;
    *outWidth = 0;
    *outHeight = 0;

    glGetIntegerv(GL_VIEWPORT, viewport);

    /* 
    * Capture the whole framebuffer. CatAppearanceUI.b0 is authored in Flash
    * stage space, but the native CatVisual is transformed by the game renderer,
    * so its framebuffer X position can therefore land on either side of the screen...
    */
    width = viewport[2];
    height = viewport[3];

    if (width <= 0 || height <= 0 || width > SCREENSHOT_MAX_DIMENSION || height > SCREENSHOT_MAX_DIMENSION || width > 0x7FFFFFFF / height)
    {
        AddDebugMessage("Screenshot failed: Invalid OpenGL viewport!");
        return 0;
    }

    pixelCount = (size_t)width * (size_t)height;

    if (pixelCount > SCREENSHOT_MAX_PIXELS)
    {
        AddDebugMessage("Screenshot failed: Viewport is too large!");
        return 0;
    }

    pixels = (uint8_t*)malloc(pixelCount * 4U);

    if (!pixels)
    {
        AddDebugMessage("Screenshot failed: Not enough memory!");
        return 0;
    }

    /* This hook runs after the scene has rendered but before the window swap...
    * Read the current back buffer instead of GL_FRONT: Front-buffer contents
    * can lag indefinitely under flip-model presentation, caused the white
    * matte pass to keep seeing the preceding black frame on some systems I think...
    */
    doubleBuffered = GL_FALSE;
    glGetBooleanv(GL_DOUBLEBUFFER, &doubleBuffered);
    captureBuffer = doubleBuffered ? GL_BACK : GL_FRONT;

    glFinish();
    glGetIntegerv(GL_PACK_ALIGNMENT, &previousPackAlignment);
    glGetIntegerv(GL_READ_BUFFER, &previousReadBuffer);
    glReadBuffer(captureBuffer);
    glPixelStorei(GL_PACK_ALIGNMENT, 1);
    glReadPixels(viewport[0], viewport[1], width, height, GL_RGBA, GL_UNSIGNED_BYTE, pixels);
    glPixelStorei(GL_PACK_ALIGNMENT, previousPackAlignment);
    glReadBuffer((GLenum)previousReadBuffer);

    *outPixels = pixels;
    *outWidth = width;
    *outHeight = height;
    return 1;
}

static int ScreenshotMedian3(int first, int second, int third)
{
    if (first > second)
    {
        int temporary = first;
        first = second;
        second = temporary;
    }

    if (second > third)
    {
        int temporary = second;
        second = third;
        third = temporary;
    }

    if (first > second)
    {
        second = first;
    }

    return second;
}

static int ScreenshotFramesHaveDifferentMatte(const uint8_t* blackFrame, const uint8_t* whiteFrame, int width, int height)
{
    size_t changedPixels;
    size_t pixelCount;
    size_t requiredPixels;
    size_t index;
    const uint8_t* blackPixel;
    const uint8_t* whitePixel;
    int redDifference;
    int greenDifference;
    int blueDifference;
    int medianDifference;

    if (!blackFrame || !whiteFrame || width <= 0 || height <= 0)
    {
        return 0;
    }

    pixelCount = (size_t)width * (size_t)height;
    requiredPixels = pixelCount * SCREENSHOT_MINIMUM_MATTE_COVERAGE_PERCENT / 100U;

    if (requiredPixels < SCREENSHOT_MINIMUM_COMPONENT_PIXELS)
    {
        requiredPixels = SCREENSHOT_MINIMUM_COMPONENT_PIXELS;
    }

    changedPixels = 0;

    for (index = 0; index < pixelCount; ++index)
    {
        blackPixel = blackFrame + index * 4U;
        whitePixel = whiteFrame + index * 4U;
        redDifference = (int)whitePixel[0] - (int)blackPixel[0];
        greenDifference = (int)whitePixel[1] - (int)blackPixel[1];
        blueDifference = (int)whitePixel[2] - (int)blackPixel[2];
        medianDifference = ScreenshotMedian3(redDifference, greenDifference, blueDifference);

        if (medianDifference >= SCREENSHOT_MINIMUM_MATTE_DELTA)
        {
            ++changedPixels;

            if (changedPixels >= requiredPixels)
            {
                return 1;
            }
        }
    }

    return 0;
}

static int ScreenshotFrameDimensionsMatch(int width, int height)
{
    if (width == g_screenshotFrameWidth && height == g_screenshotFrameHeight)
    {
        return 1;
    }

    AddDebugMessage("Screenshot failed: The viewport changed during capture!");
    return 0;
}

static int ScreenshotRoundedDivide(int numerator, int denominator)
{
    if (denominator <= 0)
    {
        return 0;
    }

    if (numerator >= 0)
    {
        return (numerator + denominator / 2) / denominator;
    }

    return -((-numerator + denominator / 2) / denominator);
}

static uint8_t ReconstructIsolatedScreenshotAlpha(const uint8_t* visibleBlackPixel, const uint8_t* visibleWhitePixel, const uint8_t* backgroundBlackPixel, const uint8_t* backgroundWhitePixel)
{
    int channelAlpha[3];
    int validChannels;
    int backgroundRange;
    int visibleRange;
    int alpha;
    int channel;

    validChannels = 0;

    for (channel = 0; channel < 3; ++channel)
    {
        backgroundRange = (int)backgroundWhitePixel[channel] - (int)backgroundBlackPixel[channel];

        if (backgroundRange < SCREENSHOT_MINIMUM_TRANSMISSION_RANGE)
        {
            continue;
        }

        visibleRange = (int)visibleWhitePixel[channel] - (int)visibleBlackPixel[channel];

        if (visibleRange < 0)
        {
            visibleRange = 0;
        }

        if (visibleRange > backgroundRange)
        {
            visibleRange = backgroundRange;
        }

        alpha = 255 - (visibleRange * 255 + backgroundRange / 2) / backgroundRange;

        if (alpha < 0) alpha = 0;
        if (alpha > 255) alpha = 255;
        channelAlpha[validChannels++] = alpha;
    }

    if (validChannels == 0)
    {
        return 0U;
    }

    if (validChannels == 1)
    {
        return (uint8_t)channelAlpha[0];
    }

    if (validChannels == 2)
    {
        return (uint8_t)((channelAlpha[0] + channelAlpha[1] + 1) / 2);
    }

    return (uint8_t)ScreenshotMedian3(channelAlpha[0], channelAlpha[1], channelAlpha[2]);
}

static uint8_t ReconstructIsolatedScreenshotColorChannel(uint8_t visibleBlackValue, uint8_t visibleWhiteValue, uint8_t backgroundBlackValue, uint8_t backgroundWhiteValue, uint8_t alpha)
{
    int backgroundRange;
    int denominator;
    int blackEstimate;
    int whiteEstimate;
    int value;

    if (alpha == 0U)
    {
        return 0U;
    }

    backgroundRange = (int)backgroundWhiteValue - (int)backgroundBlackValue;

    if (backgroundRange < SCREENSHOT_MINIMUM_TRANSMISSION_RANGE)
    {
        return 0U;
    }

    denominator = backgroundRange * (int)alpha;
    blackEstimate = ScreenshotRoundedDivide(((int)visibleBlackValue - (int)backgroundBlackValue) * 65025, denominator);
    whiteEstimate = 255 + ScreenshotRoundedDivide(((int)visibleWhiteValue - (int)backgroundWhiteValue) * 65025, denominator);

    if (blackEstimate < 0) blackEstimate = 0;
    if (blackEstimate > 255) blackEstimate = 255;
    if (whiteEstimate < 0) whiteEstimate = 0;
    if (whiteEstimate > 255) whiteEstimate = 255;

    value = (blackEstimate + whiteEstimate + 1) / 2;
    return (uint8_t)value;
}

int CaptureScreenshotBlackPass(void)
{
    uint8_t* pixels;
    int width;
    int height;

    pixels = NULL;
    width = 0;
    height = 0;

    if (!ReadScreenshotCurrentFrame(&pixels, &width, &height))
    {
        return -1;
    }

    free(g_screenshotVisibleBlackFrame);
    g_screenshotVisibleBlackFrame = pixels;
    g_screenshotFrameWidth = width;
    g_screenshotFrameHeight = height;
    return 1;
}

int CaptureScreenshotWhitePass(void)
{
    uint8_t* pixels;
    int width;
    int height;

    if (!g_screenshotVisibleBlackFrame || g_screenshotFrameWidth <= 0 || g_screenshotFrameHeight <= 0)
    {
        AddDebugMessage("Screenshot failed: The visible black pass was not captured!");
        return -1;
    }

    pixels = NULL;
    width = 0;
    height = 0;

    if (!ReadScreenshotCurrentFrame(&pixels, &width, &height))
    {
        return -1;
    }

    if (!ScreenshotFrameDimensionsMatch(width, height))
    {
        free(pixels);
        return -1;
    }

    if (!ScreenshotFramesHaveDifferentMatte(g_screenshotVisibleBlackFrame, pixels, width, height))
    {
        free(pixels);
        return 0;
    }

    free(g_screenshotVisibleWhiteFrame);
    g_screenshotVisibleWhiteFrame = pixels;
    return 1;
}

int CaptureScreenshotBackgroundBlackPass(void)
{
    uint8_t* pixels;
    int width;
    int height;

    if (!g_screenshotVisibleBlackFrame || !g_screenshotVisibleWhiteFrame || g_screenshotFrameWidth <= 0 || g_screenshotFrameHeight <= 0)
    {
        AddDebugMessage("Screenshot failed: The visible render passes were not captured!");
        return -1;
    }

    pixels = NULL;
    width = 0;
    height = 0;

    if (!ReadScreenshotCurrentFrame(&pixels, &width, &height))
    {
        return -1;
    }

    if (!ScreenshotFrameDimensionsMatch(width, height))
    {
        free(pixels);
        return -1;
    }

    free(g_screenshotBackgroundBlackFrame);
    g_screenshotBackgroundBlackFrame = pixels;
    return 1;
}

int CaptureCatScreenshot(void)
{
    SYSTEMTIME now;
    uint8_t* backgroundWhiteFrame;
    uint8_t* alphaMask;
    uint8_t* output;
    const uint8_t* visibleBlackPixel;
    const uint8_t* visibleWhitePixel;
    const uint8_t* backgroundBlackPixel;
    const uint8_t* backgroundWhitePixel;
    uint8_t* outputPixel;
    char directory[MAX_PATH + 32];
    char outputPath[800];
    size_t pixelCount;
    size_t index;
    size_t sourceIndex;
    size_t outputIndex;
    int width;
    int height;
    int x;
    int y;
    int left;
    int bottom;
    int right;
    int top;
    int area;
    int outputWidth;
    int outputHeight;
    int outputX;
    int outputY;
    int sourceX;
    int sourceY;
    int success;
    uint8_t alpha;

    if (!g_screenshotVisibleBlackFrame || !g_screenshotVisibleWhiteFrame || !g_screenshotBackgroundBlackFrame || g_screenshotFrameWidth <= 0 || g_screenshotFrameHeight <= 0)
    {
        AddDebugMessage("Screenshot failed: The required isolation passes were not captured!");
        return -1;
    }

    backgroundWhiteFrame = NULL;
    width = 0;
    height = 0;

    if (!ReadScreenshotCurrentFrame(&backgroundWhiteFrame, &width, &height))
    {
        return -1;
    }

    if (!ScreenshotFrameDimensionsMatch(width, height))
    {
        free(backgroundWhiteFrame);
        return -1;
    }

    if (!ScreenshotFramesHaveDifferentMatte(g_screenshotBackgroundBlackFrame, backgroundWhiteFrame, width, height))
    {
        free(backgroundWhiteFrame);
        return 0;
    }

    if (!EnsureScreenshotDirectory(directory, sizeof(directory)))
    {
        free(backgroundWhiteFrame);
        return -1;
    }

    pixelCount = (size_t)width * (size_t)height;
    alphaMask = (uint8_t*)malloc(pixelCount);

    if (!alphaMask)
    {
        free(backgroundWhiteFrame);
        AddDebugMessage("Screenshot failed: Not enough memory for alpha reconstruction!");
        return -1;
    }

    for (y = 0; y < height; ++y)
    {
        for (x = 0; x < width; ++x)
        {
            index = (size_t)y * (size_t)width + (size_t)x;
            visibleBlackPixel = g_screenshotVisibleBlackFrame + index * 4U;
            visibleWhitePixel = g_screenshotVisibleWhiteFrame + index * 4U;
            backgroundBlackPixel = g_screenshotBackgroundBlackFrame + index * 4U;
            backgroundWhitePixel = backgroundWhiteFrame + index * 4U;
            alpha = ReconstructIsolatedScreenshotAlpha(visibleBlackPixel, visibleWhitePixel, backgroundBlackPixel, backgroundWhitePixel);

            if (alpha <= SCREENSHOT_ALPHA_THRESHOLD)
            {
                alpha = 0U;
            }

            alphaMask[index] = alpha;
        }
    }

    left = width;
    bottom = height;
    right = -1;
    top = -1;
    area = 0;

    for (y = 0; y < height; ++y)
    {
        for (x = 0; x < width; ++x)
        {
            index = (size_t)y * (size_t)width + (size_t)x;

            if (alphaMask[index] == 0U)
            {
                continue;
            }

            ++area;

            if (x < left) left = x;
            if (x > right) right = x;
            if (y < bottom) bottom = y;
            if (y > top) top = y;
        }
    }

    if (area < SCREENSHOT_MINIMUM_COMPONENT_PIXELS || right < left || top < bottom)
    {
        free(alphaMask);
        free(backgroundWhiteFrame);
        AddDebugMessage("Screenshot failed: Cat pixels were not found after background isolation!");
        return -1;
    }

    left -= SCREENSHOT_PADDING;
    bottom -= SCREENSHOT_PADDING;
    right += SCREENSHOT_PADDING;
    top += SCREENSHOT_PADDING;

    if (left < 0) { left = 0; }
    if (bottom < 0) { bottom = 0; }
    if (right >= width) { right = width - 1; }
    if (top >= height) { top = height - 1; }

    outputWidth = right - left + 1;
    outputHeight = top - bottom + 1;
    output = (uint8_t*)calloc((size_t)outputWidth * (size_t)outputHeight, 4U);

    if (!output)
    {
        free(alphaMask);
        free(backgroundWhiteFrame);
        AddDebugMessage("Screenshot failed: Not enough memory for PNG!");
        return -1;
    }

    for (outputY = 0; outputY < outputHeight; ++outputY)
    {
        sourceY = top - outputY;

        for (outputX = 0; outputX < outputWidth; ++outputX)
        {
            sourceX = left + outputX;
            sourceIndex = (size_t)sourceY * (size_t)width + (size_t)sourceX;
            alpha = alphaMask[sourceIndex];

            if (alpha == 0U)
            {
                continue;
            }

            visibleBlackPixel = g_screenshotVisibleBlackFrame + sourceIndex * 4U;
            visibleWhitePixel = g_screenshotVisibleWhiteFrame + sourceIndex * 4U;
            backgroundBlackPixel = g_screenshotBackgroundBlackFrame + sourceIndex * 4U;
            backgroundWhitePixel = backgroundWhiteFrame + sourceIndex * 4U;
            outputIndex = ((size_t)outputY * (size_t)outputWidth + (size_t)outputX) * 4U;
            outputPixel = output + outputIndex;
            outputPixel[0] = ReconstructIsolatedScreenshotColorChannel(visibleBlackPixel[0], visibleWhitePixel[0], backgroundBlackPixel[0], backgroundWhitePixel[0], alpha);
            outputPixel[1] = ReconstructIsolatedScreenshotColorChannel(visibleBlackPixel[1], visibleWhitePixel[1], backgroundBlackPixel[1], backgroundWhitePixel[1], alpha);
            outputPixel[2] = ReconstructIsolatedScreenshotColorChannel(visibleBlackPixel[2], visibleWhitePixel[2], backgroundBlackPixel[2], backgroundWhitePixel[2], alpha);
            outputPixel[3] = alpha;
        }
    }

    GetLocalTime(&now);
    snprintf(outputPath, sizeof(outputPath), "%s\\cat_%04u%02u%02u-%02u%02u%02u-%03u.png", directory, (unsigned int)now.wYear, (unsigned int)now.wMonth, (unsigned int)now.wDay, (unsigned int)now.wHour, (unsigned int)now.wMinute, (unsigned int)now.wSecond, (unsigned int)now.wMilliseconds);
    success = WriteRgbaPng(outputPath, output, outputWidth, outputHeight);
    free(output);
    free(alphaMask);
    free(backgroundWhiteFrame);

    if (!success)
    {
        AddDebugMessage("Screenshot failed while writing the PNG file!");
        return -1;
    }

    AddDebugMessage("Saved cat .png: %s", AppearanceFileName(outputPath));
    Log("Captured four-pass isolated cat PNG to %s (%dx%d); scene vignette, UI, and cursor were excluded!", outputPath, outputWidth, outputHeight);
    return 1;
}

int ExportAppearance(const uint8_t* parts)
{
    SYSTEMTIME now;
    char directory[MAX_PATH + 32];
    char outputPath[800];
    char text[APPEARANCE_TEXT_BUFFER_SIZE];
    DWORD written;
    HANDLE file;
    int textLength;
    int overwriting;

    if (!EnsureAppearanceDirectory(directory, sizeof(directory)))
    {
        return 0;
    }

    overwriting = g_activeAppearancePath[0] != '\0';

    if (overwriting)
    {
        snprintf(outputPath, sizeof(outputPath), "%s", g_activeAppearancePath);
    }
    else
    {
        GetLocalTime(&now);
        snprintf(outputPath, sizeof(outputPath), "%s\\cat_%04u%02u%02u-%02u%02u%02u.catstruct", directory, (unsigned int)now.wYear, (unsigned int)now.wMonth, (unsigned int)now.wDay, (unsigned int)now.wHour, (unsigned int)now.wMinute, (unsigned int)now.wSecond);
    }

    textLength = FormatAppearanceText(parts, text, sizeof(text));

    if (!textLength)
    {
        AddDebugMessage("Save failed: Text was too large!");
        return 0;
    }

    file = CreateFileA(outputPath, GENERIC_WRITE, FILE_SHARE_READ, NULL, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);

    if (file == INVALID_HANDLE_VALUE)
    {
        AddDebugMessage("Save failed: Could not create the .catstruct file!");
        Log("Export failed for %s (error %lu)", outputPath, GetLastError());
        return 0;
    }

    written = 0;

    if (!WriteFile(file, text, (DWORD)textLength, &written, NULL) || written != (DWORD)textLength)
    {
        CloseHandle(file);
        AddDebugMessage("Save failed while writing the .catstruct file!");
        return 0;
    }

    CloseHandle(file);
    snprintf(g_activeAppearancePath, sizeof(g_activeAppearancePath), "%s", outputPath);
    AddDebugMessage(overwriting ? "Updated: %s" : "Saved: %s", AppearanceFileName(outputPath));
    Log("Exported cat to %s", outputPath);
    return 1;
}